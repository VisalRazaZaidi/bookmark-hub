// Local sharing: builds plain text, Markdown or a standard Netscape bookmark
// file from the bookmarks already loaded in the page. No network, no
// permissions, no server. Loaded before js/app.js.
(() => {
  const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

  function shortUrl(url) {
    try {
      const u = new URL(url);
      const p = (u.pathname + u.search).replace(/\/$/, "");
      return ((u.hostname.replace(/^www\./, "") + p) || url).slice(0, 90);
    } catch { return String(url || "").slice(0, 90); }
  }

  function titleOf(it) {
    const t = String(it.title || "").replace(/\s+/g, " ").trim();
    return t || shortUrl(it.url);
  }

  // Keep the first copy of each URL; screen order wins.
  function dedupe(items) {
    const seen = new Set();
    return items.filter((it) => {
      const k = it.dupKey || it.url;
      if (seen.has(k)) return false;
      seen.add(k);
      return true;
    });
  }

  // Group in screen order by the immediate folder. Falling back to the folder
  // name keeps imported files and live bookmarks consistent.
  function groups(items) {
    const map = new Map();
    for (const it of items) {
      const ids = Array.isArray(it.pathIds) ? it.pathIds : [];
      const key = ids.length ? ids[ids.length - 1] : (it.path && it.path.length ? it.path[it.path.length - 1] : "Bookmarks");
      const name = (it.path && it.path.length ? it.path[it.path.length - 1] : "") || "Bookmarks";
      if (!map.has(key)) map.set(key, { name, items: [] });
      map.get(key).items.push(it);
    }
    return [...map.values()];
  }

  function text(items, { group = true, dedupe: dedupeOn = true } = {}) {
    const list = dedupeOn ? dedupe(items) : items;
    const line = (it) => `${titleOf(it)} — ${it.url}`;
    if (!group) return list.map(line).join("\n");
    return groups(list).map((g) => `${g.name}\n${g.items.map(line).join("\n")}`).join("\n\n");
  }

  const mdTitle = (it) => titleOf(it).replace(/([\[\]])/g, "\\$1");
  const mdUrl = (url) => String(url).replace(/ /g, "%20").replace(/\(/g, "%28").replace(/\)/g, "%29");

  function markdown(items, { group = true, dedupe: dedupeOn = true } = {}) {
    const list = dedupeOn ? dedupe(items) : items;
    const line = (it) => `- [${mdTitle(it)}](${mdUrl(it.url)})`;
    if (!group) return list.map(line).join("\n");
    return groups(list).map((g) => `## ${g.name}\n\n${g.items.map(line).join("\n")}`).join("\n\n");
  }

  // Netscape bookmark file: importable by Chrome, Edge, Firefox and Safari and
  // still readable when opened directly.
  function buildTree(items, folders, rootId, rootName) {
    const root = { name: rootName, items: [], children: new Map() };
    for (const it of items) {
      let ids = Array.isArray(it.pathIds) ? it.pathIds : [];
      if (rootId) {
        const at = ids.indexOf(rootId);
        ids = at >= 0 ? ids.slice(at + 1) : [];
      }
      let node = root;
      for (const fid of ids) {
        const name = folders?.get?.(fid)?.title || "Folder";
        if (!node.children.has(fid)) node.children.set(fid, { name, items: [], children: new Map() });
        node = node.children.get(fid);
      }
      node.items.push(it);
    }
    return root;
  }

  function treeBody(node, indent) {
    let out = "";
    for (const it of node.items) {
      const added = it.added ? ` ADD_DATE="${Math.floor(it.added / 1000)}"` : "";
      out += `${indent}<DT><A HREF="${esc(it.url)}"${added}>${esc(titleOf(it))}</A>\n`;
    }
    for (const child of node.children.values()) {
      out += `${indent}<DT><H3>${esc(child.name)}</H3>\n`;
      out += `${indent}<DL><p>\n`;
      out += treeBody(child, indent + "    ");
      out += `${indent}</DL><p>\n`;
    }
    return out;
  }

  function netscape(items, { folders, root, rootId = null, dedupe: dedupeOn = true } = {}) {
    const list = dedupeOn ? dedupe(items) : items;
    const tree = buildTree(list, folders, rootId, root || "Shared bookmarks");
    return [
      "<!DOCTYPE NETSCAPE-Bookmark-file-1>",
      "<!-- Generated by Bookmark Hub. Import with your browser's bookmark manager. -->",
      '<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">',
      "<TITLE>Bookmarks</TITLE>",
      `<H1>${esc(tree.name)}</H1>`,
      "<DL><p>",
      treeBody(tree, "    "),
      "</DL><p>",
      "",
    ].join("\n");
  }

  function preview(body, lines = 3) {
    const all = String(body).split("\n");
    return { text: all.slice(0, lines).join("\n"), more: Math.max(0, all.length - lines) };
  }

  async function copy(body) {
    try {
      await navigator.clipboard.writeText(body);
      return true;
    } catch {
      try {
        const ta = document.createElement("textarea");
        ta.value = body;
        ta.setAttribute("readonly", "");
        ta.style.cssText = "position:fixed;top:0;left:0;opacity:0;pointer-events:none";
        document.body.appendChild(ta);
        ta.select();
        const ok = document.execCommand("copy");
        ta.remove();
        return ok;
      } catch { return false; }
    }
  }

  function download(name, mime, body) {
    const url = URL.createObjectURL(new Blob([body], { type: mime }));
    const a = document.createElement("a");
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  }

  function filename(label, date = new Date()) {
    const slug = String(label || "")
      .normalize("NFKD")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40)
      .replace(/-+$/g, "");
    const iso = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
    return `bookmark-hub-${slug || "bookmarks"}-${iso}.html`;
  }

  function canNative() {
    if (typeof navigator.share !== "function") return false;
    try { return !navigator.canShare || navigator.canShare({ text: "Bookmark Hub" }); } catch { return true; }
  }

  // "shared" | "abort" | "unsupported" | "failed"
  async function shareNative({ title, text: body, url }) {
    if (!canNative()) return "unsupported";
    try {
      await navigator.share(url ? { title, url } : { title, text: body });
      return "shared";
    } catch (e) {
      return e && e.name === "AbortError" ? "abort" : "failed";
    }
  }

  globalThis.BHShare = { text, markdown, netscape, preview, copy, download, filename, canNative, shareNative, dedupe, titleOf };
})();
